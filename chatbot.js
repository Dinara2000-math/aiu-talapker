// 7) OpenAI шақыру (егер кілт болса) немесе кіріктірілген кеңесші
async function getSmartReply(userMessage) {
  // Егер OpenAI кілті қойылмаған немесе default болса, бірден адам сияқты моторымызды қолданамыз!
  if (!OPENAI_API_KEY || OPENAI_API_KEY === "YOUR_OPENAI_API_KEY_HERE" || OPENAI_API_KEY.length < 20) {
    // 600-900ms жасанды кідіріс жасап, адам жазып жатқандай әсер береміз
    await new Promise(r => setTimeout(r, 700));
    return getHumanAdvisorAdvice(userMessage);
  }

  chatHistory.push({ role: "user", content: userMessage });
  const recentHistory = chatHistory.slice(-8);
  const messages = [
    { role: "system", content: buildSystemPrompt() },
    ...recentHistory
  ];

  try {
    const response = await fetch("https://api.openai.com/v1/chat/completions", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "Authorization": `Bearer ${OPENAI_API_KEY}`
      },
      body: JSON.stringify({
        model: OPENAI_MODEL,
        messages: messages,
        max_tokens: 700,
        temperature: 0.75
      })
    });

    if (!response.ok) {
      console.warn("OpenAI response not ok, fallback to human engine.");
      return getHumanAdvisorAdvice(userMessage);
    }

    const data = await response.json();
    const reply = data.choices?.[0]?.message?.content;
    if (!reply) return getHumanAdvisorAdvice(userMessage);

    chatHistory.push({ role: "assistant", content: reply });
    return formatReply(reply);
  } catch (err) {
    console.warn("OpenAI fetch failed, fallback to human engine:", err);
    return getHumanAdvisorAdvice(userMessage);
  }
}

function formatReply(text) {
  return text
    .replace(/\*\*(.+?)\*\*/g, "<b>$1</b>")
    .replace(/^[-•]\s+(.+)$/gm, "<li>$1</li>")
    .replace(/(<li>.*<\/li>\n?)+/g, match => "<ul>" + match + "</ul>")
    .replace(/\n/g, "<br>")
    .replace(/<br><ul>/g, "<ul>")
    .replace(/<\/ul><br>/g, "</ul>")
    .replace(/\+7\s*702\s*485\s*5036/g, '<a class="blink" href="tel:+77024855036">+7 702 485 5036</a>')
    .replace(/@aiu_shymkent/g, '<a class="blink" href="https://www.instagram.com/aiu_shymkent/" target="_blank" rel="noopener">@aiu_shymkent</a>');
}

// 8) Хабарлама жіберу
async function send(text) {
  text = text.trim();
  if (!text || isSending) return;

  isSending = true;
  addMsg(text, true);
  bin.value = "";
  bin.disabled = true;

  const typingEl = addTyping();

  try {
    const reply = await getSmartReply(text);
    removeTyping(typingEl);
    addMsg(reply);
  } catch (e) {
    removeTyping(typingEl);
    addMsg(getHumanAdvisorAdvice(text));
  }

  bin.disabled = false;
  bin.focus();
  isSending = false;
}

